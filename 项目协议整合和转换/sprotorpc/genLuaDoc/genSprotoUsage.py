import json
import os
import sys
from typing import Dict, List

"""
1. 需要 genSproto2LuaDoc.py 首先执行，生成如下
    * 1.1 doc_globalProtoCol.json 协议列表
    * 1.2 doc_globalStructs.json 协议结构
    * 1.3 doc_globalStructsFieldTypeMap.json
2. 读取上面的文件，从 doc_globalProtoCol.json 中获得全部 c2s的协议，json 中格式为
    {
        "name": "awardAchievementBox",
        "fileName": "achievementProto.lua",
        "comment": "领取成就宝箱奖励",
        "msgForward": "c2s",
        "id": "4401",
        "request": {
            "fields": [
                {
                    "name": "boxId",
                    "type": "integer",
                    "comment": "宝箱ID",
                    "convertToType": "integer"
                }
            ],
            "requestOnlyName": "AwardAchievementBoxRequest"
        },
        "response": {
            "fields": [
                {
                    "name": "ress",
                    "type": "*SPComRes",
                    "comment": "获得的资源",
                    "convertToType": "SPComRes[]"
                }
            ],
            "requestOnlyName": "AwardAchievementBoxResponse"
        }
    }
3. 要生成的 useage 函数格式
    function(boxId)
        ---@type AwardAchievementBoxRequest
        local request = {
            boxId = boxId
        }
        return {            
            name = "awardAchievementBox",
            request = request,
            cmd = "usage_achievementProto.awardAchievementBox 1001"
        }
    end
"""

##########################################################################################################
GLOBAL_PROTO_COL = None
GLOBAL_STRUCTS = None
GLOBAL_STRUCTS_FIELD_TYPE_MAP = None
##########################################################################################################

def loadJsonFile(filepath: str) -> Dict:
    """加载 JSON 文件"""
    with open(filepath, 'r', encoding='utf-8') as f:
        return json.load(f)
# end for loadJsonFile

def getParamList(fields: List[Dict]) -> str:
    """生成函数参数列表"""
    return ', '.join([field['name'] for field in fields])
# end for getParamList

def getRequestFields(fields: List[Dict], indent) -> List[str]:
    """生成请求字段列表"""
    content: List[str] = []
    for field in fields:
        name = field['name']
        content.append(f"{indent}{name} = {name},")
    return content
# end for getRequestFields

def generateUsageFunction(proto: Dict, outputFileName: str) -> List[str]:
    """生成单个协议的 usage 函数"""
    # 使用缩进控制
    indent1 = " " * 4  # 第一层缩进
    indent2 = " " * 8  # 第二层缩进

    name = proto['name']
    request = proto['request']
    paramList = getParamList(request['fields'])
    requestFields = getRequestFields(request['fields'], indent2)
    
    content: List[str] = []
    content.append(f"{outputFileName}.{proto['name']} = function({paramList})")
    content.append(f"{indent1}---@type {request['requestOnlyName']}")
    content.append(f"{indent1}local request = {{")

    content.extend(requestFields)    
    
    content.append(f"{indent1}}}")
    content.append(f"{indent1}return {{")
    content.append(f"{indent2}name = \"{name}\",")
    content.append(f"{indent2}request = request,")
    content.append(f"{indent2}cmd = \"{outputFileName}.{name} {paramList}\"")
    content.append(f"{indent1}}}")
    content.append(f"end")

    return content
# end for generateUsageFunction

def generateAllUsages(outputDir: str):
    """生成所有 c2s 协议的 usage 函数"""
        
    # 按文件名分组
    fileName2protos: Dict[str, List] = {}
    for protoId, proto in GLOBAL_PROTO_COL.items():
        if proto['msgForward'] != 'c2s':
            continue        
        fileName = proto['fileName'].replace('proto.lua', '').replace('Proto.lua', '')
        if not fileName:
            continue
        if fileName not in fileName2protos:
            fileName2protos[fileName] = []
        fileName2protos[fileName].append(proto)

    # print(f"file2protos: {file2protos}")

    for fileName, protos in fileName2protos.items():
        outputFileName = f"usage_{fileName}"
        outputContent = []
        
        # 添加文件头
        outputContent.append(f"-- Generated by genSprotoUsage.py")
        outputContent.append(f"-- Do not edit this file manually!")
        outputContent.append("")
        outputContent.append(f"local {outputFileName} = {{}}")
        outputContent.append("")

        # 生成每个协议的 usage 函数
        for proto in protos:
            tmpContent = generateUsageFunction(proto, outputFileName)
            outputContent.extend(tmpContent)
            outputContent.append("")

        # 添加返回语句
        outputContent.append(f"return {outputFileName}")

        # 写入文件
        outputPath = os.path.join(outputDir, f"{outputFileName}.lua")
        with open(outputPath, 'w', encoding='utf-8') as f:
            f.write('\n'.join(outputContent))
    return
# end for generateAllUsages

##########################################################################################################
def main():
    if len(sys.argv) < 2:
        print("Error: Missing directory argument")
        print("Usage: python genSprotoUsage.py <directory>")
        sys.exit(1)

    # 获取命令行参数中的目录
    inputDir = sys.argv[1]

    globalProtoColPath = os.path.join(inputDir, "luadoc/doc_globalProtoCol.json")
    globalStructs = os.path.join(inputDir, "luadoc/doc_globalStructs.json")
    globalStructsFieldTypeMap = os.path.join(inputDir, "luadoc/doc_globalStructsFieldTypeMap.json")

    outputDir = os.path.join(inputDir, 'usage_output')
    if not os.path.exists(outputDir):
        os.makedirs(outputDir)
        print(f"Created output directory: {outputDir}")

    # 声明使用全局变量
    global GLOBAL_PROTO_COL
    global GLOBAL_STRUCTS 
    global GLOBAL_STRUCTS_FIELD_TYPE_MAP

    GLOBAL_PROTO_COL = loadJsonFile(globalProtoColPath)
    # print(f"Load GLOBAL_PROTO_COL: {GLOBAL_PROTO_COL}")
    GLOBAL_STRUCTS = loadJsonFile(globalStructs)
    # print(f"Load GLOBAL_STRUCTS: {GLOBAL_STRUCTS}")
    GLOBAL_STRUCTS_FIELD_TYPE_MAP = loadJsonFile(globalStructsFieldTypeMap)
    # print(f"Load GLOBAL_STRUCTS_FIELD_TYPE_MAP: {GLOBAL_STRUCTS_FIELD_TYPE_MAP}")

    generateAllUsages(outputDir)
# end for main

if __name__ == '__main__':
    main()