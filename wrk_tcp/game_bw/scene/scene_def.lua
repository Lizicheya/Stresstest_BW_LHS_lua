-- 从坐标组随机取一个点,返回 x, y
function M.pick_pos(list)
    if type(list) ~= "table" or #list == 0 then return nil, nil end
    local p = list[math.random(1, #list)]
    return p[1], p[2]
end

-- 随机取一个资源类型(1001 等)
function M.pick_res_type()
    local keys = M.res_type_keys
    if #keys == 0 then return nil end
    return keys[math.random(1, #keys)]
end

-- 按场景配置 id 取迁城点组
function M.get_move_pos_by_scene(scene_cfg_id)
    return M.move_pos_dict[scene_cfg_id]
end

-- 按场景配置 id 取联盟要塞 id
function M.get_alliance_target_by_scene(scene_cfg_id)
    local list = M.allianct_target_dic[scene_cfg_id]
    return list and list[1] or nil
end

-- 判断错误码是否属于「可忽略」集合
function M.is_ignore_err(err_code)
    return M.IGNORE_ERRS[err_code] == true
end

return M
